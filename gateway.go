// Envelope bounds for commit message generation.
const (
	maxGenAttempts = 2   // The maximum number of provider calls per message (1 initial + retries with feedback).
	minConfidence  = 0.0 // The minimum allowed confidence score in the envelope.
	maxConfidence  = 1.0 // The maximum allowed confidence score in the envelope.
)

// completeChat sends req to client and returns the decoded structured result.
// It is a package-level seam so tests can swap out the external AI call.
var completeChat = func(ctx context.Context, client *tsaiclient.Client, req *tsaiclient.Request) (tsaiclient.JSONResult, error) {
	// Complete and decode the request exactly once; retries are the caller's policy.
	return client.CompleteJSON(ctx, req)
}

// genMessage returns the commit message and model confidence score in [0, 1]
// generated by client for diff. It attempts up to maxGenAttempts times,
// feeding message-format validation and truncation failures back to the model
// between attempts while failing immediately on provider, envelope-decode,
// findings-count, or confidence-range errors. The sessionID is attached to
// every request so retries and repeated invocations for the same diff share
// one provider endpoint and prompt cache. It returns an error if all attempts
// fail.
func genMessage(ctx context.Context, client *tsaiclient.Client, diff string, sessionID string) (string, float64, error) {
	// Build prompt
	prompt := buildPrompt(diff)
	// Attempt generation up to maxGenAttempts times.
	var lastErr error
	for attempt := 1; attempt <= maxGenAttempts; attempt++ {
		// Build the completion request for the current prompt.
		req, err := tsaiclient.NewRequest(prompt)
		// Return the error if building the request fails.
		if err != nil {
			return "", 0, tserr.Op(&tserr.OpArgs{Op: "new request", Fn: "AI client", Err: err})
		}
		// Attach the sticky routing key shared by every attempt and regeneration.
		req = req.WithSessionID(sessionID)
		// Call the provider to produce and decode a structured commit envelope.
		res, err := completeChat(ctx, client, req)
		// Return the error if the provider call or envelope decoding fails.
		if err != nil {
			return "", 0, tserr.Op(&tserr.OpArgs{Op: "complete chat", Fn: "AI client", Err: err})
		}
		// Extract the raw commit message and confidence from the envelope.
		raw, confidence, err := extractEnvelope(res.Envelope)
		// Return immediately when the envelope does not satisfy the contract.
		if err != nil {
			return "", 0, err
		}
		// Clean wrapper formatting the model may have added around the message.
		content := cleanMessage(raw)
		// Return an error when nothing remains after cleaning; not retryable.
		if content == "" {
			return "", 0, tserr.Empty("AI client commit message")
		}
		// Validate the generated message.
		validateErr := validateMessage(content)
		// Accept the message if it validates and was not truncated.
		if validateErr == nil && !res.Truncated {
			return content, confidence, nil
		}
		// Build feedback from the validation failure and/or truncation.
		var feedback string
		// Report validation failure as a failure when the message is invalid.
		if validateErr != nil {
			feedback = "\n\nYour previous output was invalid: " + validateErr.Error()
		}
		// Explain truncation so the retry stays under the token limit.
		if res.Truncated {
			feedback += "\nYour previous output was cut off; be significantly more concise."
		}
		// Record the cause: prefer the validation error, fall back to truncation.
		lastErr = validateErr
		// Fall back to the truncation cause when the message itself validated.
		if lastErr == nil {
			lastErr = errors.New("output was truncated by the token limit")
		}
		// If attempts remain, ask the provider to fix its previous output.
		if attempt < maxGenAttempts {
			// Build corrective feedback for the retry prompt, including the
			// previous output and reminding the model to return the JSON envelope.
			prompt = prompt +
				feedback +
				"\nPrevious commit message:\n" + content +
				"\nRegenerate the commit message following STRICT FORMAT RULES exactly, and respond with ONLY the single JSON object."
		}
	}
	// Return an error when all attempts produced invalid messages.
	return "", 0, tserr.Op(&tserr.OpArgs{Op: "generate message", Fn: "AI client", Err: lastErr})
}

// extractEnvelope returns the single finding and confidence score in env, or
// an error if env carries zero or multiple findings or a confidence score
// outside [0, 1].
func extractEnvelope(env tsaiclient.Envelope) (string, float64, error) {
	// Return an error when the model returned no findings.
	if len(env.Findings) == 0 {
		return "", 0, tserr.Empty("AI client commit message")
	}
	// Return an error when the model returned more than one finding.
	if len(env.Findings) != 1 {
		return "", 0, tserr.EqualInt(&tserr.EqualIntArgs{
			Var:    "AI client findings count",
			Actual: int64(len(env.Findings)),
			Want:   1,
		})
	}
	// Reject NaN or infinite confidence scores.
	if math.IsNaN(env.Confidence) || math.IsInf(env.Confidence, 0) {
		return "", 0, tserr.InvalidFormat(&tserr.InvalidFormatArgs{
			F:      "AI client confidence",
			Value:  fmt.Sprintf("%v", env.Confidence),
			Detail: "expected a number between 0 and 1",
		})
	}
	// Reject confidence scores below the minimum bound.
	if env.Confidence < minConfidence {
		return "", 0, tserr.Higherf(&tserr.HigherfArgs{
			Var:        "AI client confidence",
			LowerBound: minConfidence,
			Actual:     env.Confidence,
		})
	}
	// Reject confidence scores above the maximum bound.
	if env.Confidence > maxConfidence {
		return "", 0, tserr.Lowerf(&tserr.LowerfArgs{
			Var:         "AI client confidence",
			HigherBound: maxConfidence,
			Actual:      env.Confidence,
		})
	}
	// Return the single finding and validated confidence score.
	return env.Findings[0], env.Confidence, nil
}

// cleanMessage removes markdown code fences, backticks, and
// extra wrapper formatting from s and returns the cleaned message.
func cleanMessage(s string) string {
	// Trim leading and trailing whitespace
	s = strings.TrimSpace(s)
	// Strip outer markdown code block fences (e.g. ```commit ... ``` or ``` ...)
	if strings.HasPrefix(s, "```") {
		// If there is a newline after the opening fence, remove everything up to and including it.
		// Otherwise, just remove the opening fence. In either case, remove the trailing fence.
		if idx := strings.Index(s, "\n"); idx != -1 {
			// Remove opening fence and optional language tag up to newline
			s = s[idx+1:]
		} else {
			// Remove opening fence, if no newline
			s = strings.TrimPrefix(s, "```")
		}
		// Remove trailing fence
		s = strings.TrimSuffix(strings.TrimSpace(s), "```")
	}
	// Strip one matching pair of outer quotes or backticks when the message
	// is wrapped (e.g. "..." , '...' or `...`).
	s = strings.TrimSpace(s)
	// Check that at least two characters remain to form a wrapper pair.
	if n := len(s); n >= 2 {
		// Read the first and last bytes; wrapper characters are ASCII.
		first, last := s[0], s[n-1]
		// Check that both ends carry the same wrapper character.
		if first == last && strings.ContainsRune("`\"'", rune(first)) {
			// Remove the matched wrapper pair from both ends.
			s = s[1 : n-1]
		}
	}
	// Return the message trimmed of whitespace next to the wrapper.
	return strings.TrimSpace(s)
}

// newSessionID returns a fresh random identifier used as the sticky routing
// key for one generation session.
func newSessionID() string {
	// Return a cryptographically random text identifier.
	return rand.Text()
}
